  /// Récupère la traduction selon la langue du BuildContext.
  /// En cas d'échec ou d'absence de langue, repli vers l'anglais puis le français.
  static String tr(BuildContext context, String key, [Map<String, String>? params]) {
    String lang = 'en';
    try {
      lang = Localizations.localeOf(context).languageCode.toLowerCase();
    } catch (_) {}

    String template = _strings[key]?[lang] ??
        _strings[key]?['en'] ??
        _strings[key]?['fr'] ??
        key;

    if (params != null) {
      params.forEach((paramKey, paramVal) {
        template = template.replaceAll('{$paramKey}', paramVal);
      });
    }
    return template;
  }

  /// Version synchrone sans contexte (à partir du code langue)
  static String trLang(String lang, String key, [Map<String, String>? params]) {
    final code = lang.toLowerCase();
    String template = _strings[key]?[code] ??
        _strings[key]?['en'] ??
        _strings[key]?['fr'] ??
        key;

    if (params != null) {
      params.forEach((paramKey, paramVal) {
        template = template.replaceAll('{$paramKey}', paramVal);
      });
    }
    return template;
  }
